from __future__ import annotations

from contextlib import AbstractContextManager
from datetime import datetime
from typing import List, Optional, Protocol, Tuple

from mica.domain import (
    Agent,
    ExternalEvent,
    ExternalIdentity,
    Issue,
    IssueOrigin,
    OutboxMessage,
    PlatformUser,
    Project,
    Runtime,
    RuntimeCapability,
    Squad,
    SquadMember,
    Task,
    TaskEvent,
)


class IssueRepository(Protocol):
    def add(self, issue: Issue) -> Issue: ...
    def get(self, issue_id: str) -> Optional[Issue]: ...
    def get_for_update(self, issue_id: str) -> Optional[Issue]: ...
    def save(self, issue: Issue) -> Issue: ...
    def list(self) -> List[Issue]: ...
    def delete(self, issue_id: str) -> None: ...


class TaskRepository(Protocol):
    def delete_for_issue(self, issue_id: str) -> None: ...
    def add(self, task: Task) -> Task: ...
    def enqueue_or_merge(self, task: Task) -> Tuple[Task, bool]: ...
    def get(self, task_id: str) -> Optional[Task]: ...
    def get_for_update(self, task_id: str) -> Optional[Task]: ...
    def save(self, task: Task) -> Task: ...
    def list(self, issue_id: Optional[str] = None) -> List[Task]: ...
    def claim_next(self, runtime_id: str, worker_id: str, lease_seconds: int) -> Optional[Task]: ...
    def renew_lease(self, task_id: str, worker_id: str, lease_seconds: int) -> bool: ...
    def recover_expired(self, runtime_id: str) -> List[Task]: ...
    def request_cancel(self, task_id: str) -> Optional[Task]: ...
    def find_previous(
        self, issue_id: str, agent_id: str, exclude_task_id: str
    ) -> Optional[Task]: ...
    def has_pending(
        self, issue_id: str, agent_id: str, is_leader_task: Optional[bool] = None
    ) -> bool: ...


class EventRepository(Protocol):
    def delete_for_tasks(self, task_ids: List[str]) -> None: ...
    def add(self, event: TaskEvent) -> TaskEvent: ...
    def list(self, task_id: Optional[str] = None) -> List[TaskEvent]: ...
    def list_after(self, created_at: datetime, event_id: str) -> List[TaskEvent]: ...


class AgentRepository(Protocol):
    def add(self, agent: Agent) -> Agent: ...
    def get(self, agent_id: str) -> Optional[Agent]: ...
    def list(self) -> List[Agent]: ...


class RuntimeRepository(Protocol):
    def add(self, runtime: Runtime) -> Runtime: ...
    def get(self, runtime_id: str) -> Optional[Runtime]: ...
    def list(self) -> List[Runtime]: ...


class RuntimeCapabilityRepository(Protocol):
    def replace_for_runtime(
        self, runtime_id: str, capabilities: List[RuntimeCapability]
    ) -> List[RuntimeCapability]: ...
    def list(self, runtime_id: Optional[str] = None) -> List[RuntimeCapability]: ...
    def get(self, runtime_id: str, provider: str) -> Optional[RuntimeCapability]: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> Project: ...
    def save(self, project: Project) -> Project: ...
    def get(self, project_id: str) -> Optional[Project]: ...
    def find_by_path(
        self, workspace_id: str, runtime_id: str, local_path: str
    ) -> Optional[Project]: ...
    def list(self, workspace_id: Optional[str] = None) -> List[Project]: ...


class SquadRepository(Protocol):
    def add(self, squad: Squad) -> Squad: ...
    def save(self, squad: Squad) -> Squad: ...
    def get(self, squad_id: str) -> Optional[Squad]: ...
    def list(self, workspace_id: Optional[str] = None) -> List[Squad]: ...
    def add_member(self, member: SquadMember) -> SquadMember: ...
    def remove_member(self, squad_id: str, agent_id: str) -> bool: ...
    def list_members(self, squad_id: str) -> List[SquadMember]: ...


class ChannelRepository(Protocol):
    def delete_issue_data(self, issue_id: str, event_ids: List[str]) -> None: ...

    def resolve_identity(
        self,
        channel: str,
        tenant_key: str,
        external_user_id: str,
        workspace_id: str,
        display_name: str,
    ) -> Tuple[PlatformUser, ExternalIdentity]: ...

    def reserve_event(self, event: ExternalEvent) -> Tuple[ExternalEvent, bool]: ...
    def attach_issue(
        self, channel: str, tenant_key: str, external_event_id: str, issue_id: str
    ) -> None: ...
    def add_origin(self, origin: IssueOrigin) -> IssueOrigin: ...
    def get_origin(self, issue_id: str) -> Optional[IssueOrigin]: ...
    def find_origin(
        self, channel: str, tenant_key: str, external_message_id: str
    ) -> Optional[IssueOrigin]: ...
    def add_outbox(self, message: OutboxMessage) -> OutboxMessage: ...
    def claim_outbox(self, worker_id: str, lease_seconds: int = 60) -> Optional[OutboxMessage]: ...
    def mark_outbox_sent(self, message_id: str, worker_id: str) -> bool: ...
    def retry_outbox(
        self, message_id: str, worker_id: str, error: str, delay_seconds: int
    ) -> bool: ...
    def fail_outbox(self, message_id: str, worker_id: str, error: str) -> bool: ...


class EventPublisher(Protocol):
    def publish(self, event: TaskEvent) -> None: ...


class TransactionManager(Protocol):
    def transaction(self) -> AbstractContextManager[None]: ...
